'use server';
/**
 * @fileOverview A Genkit flow for detecting AI-generated content in a given text document.
 *
 * - detectAIContent - A function that handles the AI content detection process.
 * - DetectAIContentInput - The input type for the detectAIContent function.
 * - DetectAIContentOutput - The return type for the detectAIContent function.
 */

import { ai } from '@/ai/genkit';
import { z } from 'genkit';

const DetectAIContentInputSchema = z.object({
  documentContent: z.string().describe('The full text content of the document to be analyzed for AI generation.'),
});
export type DetectAIContentInput = z.infer<typeof DetectAIContentInputSchema>;

const DetectAIContentOutputSchema = z.object({
  aiProbabilityScore: z
    .number()
    .min(0)
    .max(100)
    .describe('The overall probability that the content was AI-generated (0-100%).'),
  perplexity: z
    .number()
    .describe('A measure of how predictable the text is; lower values typically suggest AI generation. (e.g., 50-100 for human-like, <50 for AI-like)'),
  burstiness: z
    .number()
    .describe('A measure of variation in sentence length and structure; lower values typically suggest AI generation. (e.g., 0.5-1.5 for human-like, <0.5 for AI-like)'),
  sentenceAnalysis: z
    .array(
      z.object({
        sentence: z.string().describe('The analyzed sentence.'),
        aiConfidence: z
          .number()
          .min(0)
          .max(100)
          .describe('Confidence score (0-100%) that this specific sentence was AI-generated.'),
      })
    )
    .describe('Sentence-level analysis of AI generation confidence.'),
});
export type DetectAIContentOutput = z.infer<typeof DetectAIContentOutputSchema>;

export async function detectAIContent(input: DetectAIContentInput): Promise<DetectAIContentOutput> {
  return detectAIContentFlow(input);
}

const detectAIContentPrompt = ai.definePrompt({
  name: 'detectAIContentPrompt',
  input: { schema: DetectAIContentInputSchema },
  output: { schema: DetectAIContentOutputSchema },
  prompt: `You are an expert AI content detection specialist. Your task is to analyze the provided document content and determine the likelihood that it was generated by an AI.

Provide an overall AI probability score, an estimated perplexity score, and an estimated burstiness score for the entire document. Additionally, perform a sentence-by-sentence analysis, providing a confidence score for each sentence regarding its AI origin.

Definitions:
- **AI Probability Score**: A percentage (0-100%) indicating the overall chance the document is AI-generated. Higher scores mean higher probability of AI origin.
- **Perplexity**: A measure of how well a probability distribution predicts a sample. In simpler terms, it assesses how predictable the text is; lower values typically suggest AI generation. (e.g., 50-100 for human-like, <50 for AI-like)
- **Burstiness**: A measure of variation in sentence length and structure; lower values typically suggest AI generation. (e.g., 0.5-1.5 for human-like, <0.5 for AI-like)

Document Content to Analyze:
\`\`\`
{{{documentContent}}}
\`\`\`

Your output must be a valid JSON object that conforms to the output schema.`,
});

const detectAIContentFlow = ai.defineFlow(
  {
    name: 'detectAIContentFlow',
    inputSchema: DetectAIContentInputSchema,
    outputSchema: DetectAIContentOutputSchema,
  },
  async (input) => {
    const {output} = await detectAIContentPrompt(input);

    if (!output) {
      throw new Error('AI did not return an output.');
    }
    return output;
  }
);
